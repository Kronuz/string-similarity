#pragma once

// STRSIM_SANITIZED is 1 when the test is built under AddressSanitizer, ThreadSanitizer or
// MemorySanitizer, which run these tests 10 to 40 times slower: tests that repeat random
// inputs run fewer repetitions there, over the same lengths and alphabets.

#if defined(__SANITIZE_ADDRESS__) || defined(__SANITIZE_THREAD__)
#define STRSIM_SANITIZED 1
#elif defined(__has_feature)
#if __has_feature(address_sanitizer) || __has_feature(thread_sanitizer) || __has_feature(memory_sanitizer)
#define STRSIM_SANITIZED 1
#endif
#endif

#ifndef STRSIM_SANITIZED
#define STRSIM_SANITIZED 0
#endif
